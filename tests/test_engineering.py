def dimensions():
    ents = []
    for y in (50, 150):
        ents.extend([Entity(type='line', start=(20, y), end=(120, y)),
                     Entity(type='line', start=(20, y-10), end=(20, y+10)),
                     Entity(type='line', start=(120, y-10), end=(120, y+10))])
    ir = DrawingIR(width=200, height=220, entities=ents)
    ocr = [{'text': '10', 'center': [70, y-15], 'box': [62, y-20, 78, y-10], 'score': .99}
           for y in (50, 150)]
    return ir, ocr


def test_dimension_conflicts_abstain_and_consistent_links_scale():
    ir, ocr = dimensions()
    result = estimate_scale(ocr, ir)
    assert result['mm_per_px'] == pytest.approx(.1)
    ocr[1]['text'] = '20'
    assert estimate_scale(ocr, ir)['status'] == 'conflict'
    assert estimate_scale(ocr[:1], ir)['mm_per_px'] is None


def test_disagreeing_ocr_rotations_cannot_overwrite_dimension():
    ir, ocr = dimensions()
    ocr.append({**ocr[0], 'text': '9', 'score': .98})
    result = estimate_scale(ocr, ir)
    assert result['mm_per_px'] is None
    assert result['ambiguous_ocr']


def test_scaling_preserves_selected_geometry_types(tmp_path):
    ir = DrawingIR(width=300, height=200, entities=build('slot', {
        'center': [100, 100], 'length': 120, 'diameter': 30, 'rotation': 22}))
    source, target = tmp_path/'source.dxf', tmp_path/'scaled.dxf'
    write_ir(ir, source)
    scale_selected_dxf(source, target, .2)
    a, b = ezdxf.readfile(source), ezdxf.readfile(target)
    assert [e.dxftype() for e in a.modelspace()] == [e.dxftype() for e in b.modelspace()]
    assert b.units == ezdxf.units.MM
    for original, scaled in zip(a.modelspace().query('ARC'), b.modelspace().query('ARC')):
        assert scaled.dxf.radius == pytest.approx(original.dxf.radius*.2)


