def test_raster_recognizes_four_holes_and_slot(tmp_path):
    _, img = drawing(tmp_path)
    ink = ink_mask(img)
    features, _ = recognize_features(ink, skeleton(ink))
    circles = [f for f in features if f.kind == "circle"]
    for center in [(70, 70), (425, 70), (70, 225), (425, 225)]:
        match = min(circles, key=lambda f: math.dist(f.params["center"], center))
        assert math.dist(match.params["center"], center) < 1
        assert abs(match.params["radius"]-15) < 1
    slots = [f for f in features if f.kind == "slot"]
    assert slots, [f.kind for f in features]
    assert slots[0].params["length"] == pytest.approx(170, abs=1.5)
    assert slots[0].params["diameter"] == pytest.approx(50, abs=1.5)


