def test_explicit_offline_entry_and_runs_are_isolated(tmp_path, monkeypatch):
    import tools.vlm
    def no_cloud(*args, **kwargs):
        pytest.fail('Explicit offline engineering pipeline called a cloud model')
    monkeypatch.setattr(tools.vlm, 'ask_vision', no_cloud)
    monkeypatch.setattr(tools.vlm, 'ask_image', no_cloud)
    from core.ensemble import run_ensemble
    image, _ = drawing(tmp_path)
    a = run_ensemble(str(image), out_dir=tmp_path/'runs', use_ocr=False, use_ai_review=False)
    b = run_ensemble(str(image), out_dir=tmp_path/'runs', use_ocr=False, use_cache=True, use_ai_review=False)
    assert a['out_dir'] != b['out_dir']
    assert a['best']['f1'] > .97 and a['template_count'] >= 5
    assert a['best']['dxf'] != b['best']['dxf']
    for result in (a, b):
        assert Path(result['best']['dxf']).is_file()
        assert (Path(result['out_dir'])/'overlay.png').is_file()
        assert (Path(result['out_dir'])/'report.json').is_file()
        assert not ezdxf.readfile(result['best']['dxf']).audit().has_errors
        delivery=Path(result['delivery']['directory'])
        assert list(delivery.iterdir())==[Path(result['delivery']['dxf'])]
        assert delivery!=Path(result['out_dir'])


def test_gui_engineering_worker_uses_selected_result(tmp_path, monkeypatch):
    # Exercise the GUI worker without requiring a native Tk display/runtime.
    import gui
    import core.ensemble
    from types import SimpleNamespace
    selected_dir = tmp_path/'unique_run'
    selected_dir.mkdir()
    selected = selected_dir/'best.dxf'
    selected.write_text('selected geometry', encoding='utf8')
    result = {'out_dir': str(tmp_path/'internal'), 'picked': 'LIBRARY', 'selected_templates': 2,
              'delivery': {'directory':str(selected_dir),'dxf':str(selected),'units':'pixels'},
              'best': {'dxf': str(selected), 'png': str(selected_dir/'best.png'), 'f1': .98},
              'proposals': {'LIBRARY': {'f1': .98, 'n_entities': 10}},
              'calibration': {'status': 'needs_review', 'mm_per_px': None}}
    monkeypatch.setattr(core.ensemble, 'run_ensemble', lambda *a, **kw: result)
    monkeypatch.setattr(gui, 'OUT_DIR', tmp_path/'output')
    app = gui.App.__new__(gui.App)
    messages, opened = [], []
    app.root = SimpleNamespace(after=lambda delay, fn, *args: fn(*args))
    app.log = messages.append
    app.open_file = opened.append
    app.run_btn = app.open_btn = SimpleNamespace(configure=lambda *a, **kw: None)
    app.worker('arbitrary_input.jpg', 'cad')
    assert app.out_dir == selected_dir
    assert opened == [str(selected_dir/'best.png')]
    assert selected.read_text(encoding='utf8') == 'selected geometry'
    assert not any('[错误]' in message for message in messages)
