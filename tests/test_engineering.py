def drawing(tmp_path, name="input.png"):
    # Independently specified raster fixture, not generated by the template code.
    img = np.full((300, 500, 3), 255, np.uint8)
    cv2.rectangle(img, (30, 30), (465, 265), (0, 0, 0), 2)
    for center in [(70, 70), (425, 70), (70, 225), (425, 225)]:
        cv2.circle(img, center, 15, (0, 0, 0), 2)
    cv2.line(img, (190, 125), (310, 125), (0, 0, 0), 2)
    cv2.line(img, (190, 175), (310, 175), (0, 0, 0), 2)
    cv2.ellipse(img, (190, 150), (25, 25), 0, 90, 270, (0, 0, 0), 2)
    cv2.ellipse(img, (310, 150), (25, 25), 0, -90, 90, (0, 0, 0), 2)
    path = tmp_path / name
    imwrite(path, img)
    return path, img


@pytest.mark.parametrize("rotation", [0, 27, 90, 153])
def test_slot_has_closed_tangent_geometry(rotation):
    entities = build("slot", {"center": [120, 120], "length": 110, "diameter": 30, "rotation": rotation})
    assert [e.type for e in entities].count("arc") == 2
    endpoints = []
    for e in entities:
        samples = sample_entity(e)
        endpoints.extend([samples[0], samples[-1]])
    for i, p in enumerate(endpoints):
        assert min(np.linalg.norm(p-q) for j, q in enumerate(endpoints) if j != i) < 1e-8
    for arc in [e for e in entities if e.type == "arc"]:
        assert (arc.end_angle-arc.start_angle) % 360 == pytest.approx(180)
        for p in (sample_entity(arc)[0], sample_entity(arc)[-1]):
            line = min((e for e in entities if e.type == "line"),
                       key=lambda e: min(math.dist(p, e.start), math.dist(p, e.end)))
            assert abs(float((p-arc.center) @ (np.array(line.end)-line.start))) < 1e-7


